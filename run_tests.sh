#!/usr/bin/env bash
# nolang — прогон всей батареи: лисп-тесты + ФОРМАЛЬНАЯ часть (Agda).
# Молчит про успех, кричит про падение. Считает, а не показывает галочки.
#
# 🔴 Agda проверяется ТОЛЬКО со снесённым .agdai — иначе проверяется кэш, а не файл.
cd "$(dirname "$0")" || exit 1
fail=0; total=0

echo "── ЛИСП: законы и проверки ──"
oracle_runs=""
for t in test/*.lisp; do
  out=$(sbcl --script "$t" 2>&1); rc=$?
  # 🔴 КОД ВОЗВРАТА ПРОВЕРЯЕТСЯ НАРАВНЕ С ТЕКСТОМ (29.07). Раньше смотрели только на слова
  # «Unhandled» и «FAIL:» — и тест, умерший ТИХО (exit 1 без этих слов), засчитывался как
  # пройденный с нулём законов. Ровно тот же род лжи, против которого заведён ЗАКОН XII:
  # инструмент, молчащий при неудаче, выдаёт непроверенное за проверенное.
  if [ $rc -ne 0 ] || echo "$out" | grep -q "Unhandled\|FAIL:"; then
    printf '%-24s ❌ УПАЛ (код %s)\n' "$t" "$rc"
    echo "$out" | grep -m2 "FAIL:\|Unhandled\|НЕ СОБРАН" | sed 's/^/    /'
    fail=$((fail+1))
  else
    n=$(echo "$out" | grep -oP 'проверено: \K\d+|проверок: \K\d+')
    printf '%-24s ✓ %s\n' "$t" "${n:+$n законов}"
    total=$((total+${n:-0}))
    r=$(echo "$out" | grep -oP 'ОРАКУЛ: сверено программ: \K\d+')
    [ -n "$r" ] && oracle_runs="$r"
  fi
done

echo "── ОРАКУЛ: реализация против доказанного ──"
if [ -n "$oracle_runs" ]; then
  printf 'модель→бинарь            ✓ сверено программ: %s, расхождений 0\n' "$oracle_runs"
  echo   "                         🔴 это ОГРАНИЧИВАЕТ расхождение числом испытаний,"
  echo   "                            а НЕ доказывает эквивалентность модели и Лиспа."
  echo   "                            Вне модели: свёртка по корням, вес, квантор, гейт, журнал."
else
  echo "оракул не прогнан — сборка: bash oracle/build.sh (это не успех)"; fail=$((fail+1))
fi

echo "── AGDA: теоремы (--safe, сборка с нуля) ──"
if command -v agda >/dev/null 2>&1; then
  rm -f formal/*.agdai                      # без этого проверяется кэш
  for a in formal/*.agda; do
    [ -e "$a" ] || continue
    # звать ИЗ formal/: agda ищет модуль по include-пути, из корня не находит
    if out=$(cd formal && timeout 600 agda --safe "$(basename "$a")" 2>&1); then
      # 🔴 Считаем УТВЕРЖДЕНИЯ УРОВНЯ МОДУЛЯ (ровно два пробела отступа), а не «теоремы»:
      # так отсекаются конструкторы типов (4 пробела) и переписанные cong/sym/trans/subst (0).
      # Но сюда всё ещё попадают ОПРЕДЕЛЕНИЯ (chk, red, live, den, _⊑_…). Отделить их
      # автоматически надёжно нельзя — подпись честная: «утверждений», не «теорем».
      #
      # ⚠️ РЕГУЛЯРКА НАРОЧНО ASCII-ONLY. Прежняя была [a-zA-Z0-9⁻¹<≡-] и дала РАЗНЫЙ счёт
      # в скрипте (27) и в интерактивной оболочке (25) ПРИ ОДИНАКОВОЙ ЛОКАЛИ: не совпали
      # meet-lower₁/₂ с подстрочными цифрами. Многобайтные символы в скобочном классе —
      # источник тихого расхождения. Совпадать надо СТРУКТУРНО: два пробела, не-пробелы, " : ".
      #
      # Теорем, посчитанных руками: Preservation 19 · BeliefMass 7 · ModuleImport 7 = 33.
      # (ModuleImport добавлен Невис 29.07: sound · necessary · bottom-needed · mono ·
      #  compose-⊓ · compose-⊥ + Preserves-⊓/⊥ как условия. Проверен мной пересборкой.)
      # (Раньше стояло 21 — занижено, считал по списку, обрезанному той самой ломаной регуляркой.)
      n=$(grep -cE '^  [^ ]+ : ' "$a")
      printf '%-24s ✓ %s утверждений уровня модуля (--safe)\n' "$a" "$n"
      total=$((total+n))
    else
      printf '%-24s ❌ НЕ СОБРАЛАСЬ\n' "$a"
      echo "$out" | tail -5 | sed 's/^/    /'
      fail=$((fail+1))
    fi
    # постулаты и дыры — отдельная проверка: --safe их не все ловит
    holes=$(grep -cE 'postulate|TERMINATING|trustMe|\{!' "$a")
    if [ "$holes" -gt 0 ]; then
      printf '%-24s ⚠ ПОСТУЛАТЫ/ДЫРЫ: %s\n' "$a" "$holes"; fail=$((fail+1))
    fi
  done
else
  echo "agda не найдена — формальная часть НЕ ПРОВЕРЕНА (это не успех)"; fail=$((fail+1))
fi

echo "────────────────────────────────────────"
if [ $fail -eq 0 ]; then
  echo "ВСЁ ЗЕЛЁНОЕ · законов, проверок и утверждений: $total   (из них теорем в Agda: 33)"
else
  echo "УПАЛО: $fail"; exit 1
fi
