# 🔴 ГЛАВНЫЙ АРТЕФАКТ ВСЕЙ ЛИНИИ: агент прерван на середине, восстановлен, продолжил —
# и его прошлый отказ не стёрт, а ВОСПРОИЗВЕДЁН. Проверяется снаружи, кодами возврата
# и содержимым журнала: изнутри Лиспа это выглядело бы как значение функции, а не как
# ответ машине.
cd "$(dirname "$0")/.."
ok=0; fail=0
out=$(sbcl --script test/subject/_demo.lisp 2>&1)

check() {  # $1 маркер, $2 описание
  if grep -qF "$1" <<<"$out"; then echo "  ✓ $2"; ok=$((ok+1))
  else echo "  ✗ $2 (нет: $1)"; fail=1; fi
}

check "BEFORE FOLDED"   "до перерыва: гейт свернул действие — веры не хватило"
check "AFTER FOLDED"    "после возврата: прежний отказ ВОСПРОИЗВЕДЁН, а не стёрт"
check "AFTER PERFORMED" "после возврата: новое свидетельство взяло порог"
check "SEAL OK"         "печать сошлась: вывод вычислен заново и совпал с записанным"

echo "ИТОГ: $ok"
exit $fail
