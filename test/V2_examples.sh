#!/usr/bin/env bash
# test/V2_examples.sh — ВИТРИНА ПРОВЕРЯЕТСЯ (этап 1, п.5). Невис, 30.07.2026.
#
# 🔴 Первое, что видит входящий, — примеры. До сегодня два из них падали с «синтаксической
#    ошибкой в строке 1» (написаны на РАННЕМ носителе, а README велел звать `run_example.sh`),
#    а третий отвергался ПО ЗАМЫСЛУ — и оба случая выглядели одинаково.
#    Здесь каждый пример прогоняется своим запускатором и сверяется с объявленным ожиданием.
#
# 🔴 Ожидания живут ОТДЕЛЬНО (examples/EXPECTED.tsv), а не в этом файле: мера и подсудимый
#    не должны править друг друга одной рукой. Сломать пример и подогнать ожидание в том же
#    ходу по-прежнему можно — но это будет видно двумя правками в разных файлах, а не одной.
set -u
cd "$(dirname "$0")/.." || exit 2
LIST=examples/EXPECTED.tsv   # имена переменных ТОЛЬКО латиницей: bash не принимает кириллические идентификаторы
ok=0; bad=0

[ -r "$LIST" ] || { echo "⛔ нет файла ожиданий: $LIST"; exit 2; }

echo "── ВИТРИНА: каждый пример даёт объявленный код ──"
while IFS=$'\t' read -r file runner want req prelude why; do
  case "$file" in ''|'#'*) continue ;; esac
  [ -r "$file" ] || { printf '  ✗ %-30s ФАЙЛА НЕТ (объявлен в ожиданиях)\n' "$file"; bad=$((bad+1)); continue; }

  # аргументы собираются из объявленных полей: прелюдия и require — каждое своё
  if [ "$runner" = "sexp" ]; then
    ./run_sexp.sh "$file" > /tmp/_v2_out.txt 2>&1
  else
    set --
    [ "${prelude:--}" != "-" ] && set -- "$@" --prelude "$prelude"
    [ "${req:--}" != "-" ] && set -- "$@" --require "$req"
    ./run_example.sh "$file" "$@" > /tmp/_v2_out.txt 2>&1
  fi
  got=$?          # 🔴 отдельной командой сразу после прогона: между ними НИЧЕГО

  if [ "$got" -eq "$want" ]; then
    printf '  ✓ %-30s код %s\n' "$(basename "$file")" "$got"; ok=$((ok+1))
  else
    printf '  ✗ %-30s ЖДАЛИ %s, ПОЛУЧИЛИ %s\n' "$(basename "$file")" "$want" "$got"
    printf '      объявлено: %s\n' "$why"
    sed -n '$p' /tmp/_v2_out.txt | sed 's/^/      последняя строка: /'
    bad=$((bad+1))
  fi
done < "$LIST"

# 🔴 ПРИМЕР БЕЗ ОЖИДАНИЯ — тоже дефект витрины: он никем не проверяется и может умереть молча.
echo "── НЕТ ЛИ ПРИМЕРОВ БЕЗ ОБЪЯВЛЕННОГО ОЖИДАНИЯ ──"
for f in examples/*.nol examples/sexp/*.nol; do
  [ -e "$f" ] || continue
  if grep -q "^$f	" "$LIST"; then :; else
    printf '  ✗ %-30s есть в витрине, но не объявлен в ОЖИДАНИЯХ\n' "$f"; bad=$((bad+1))
  fi
done
[ "$bad" -eq 0 ] && echo "  ✓ все примеры объявлены"

printf '\n── ИТОГ: %s сошлось, %s не сошлось ──\n' "$ok" "$bad"
[ "$bad" -eq 0 ] || exit 1
