#!/bin/bash
# C1_credal — вера как ИНТЕРВАЛ. Заведён 05.08.2026 вместе с самой границей.
#
# 🔴 ЗАКОН: `belief = f·c` схлопывает две независимые величины в одну, и на пороге
# «скорее так, но данных мало» становится неотличимо от «примерно поровну, данных много».
# Здесь проверяется, что интервал их различает — и что нижняя граница СОВПАДАЕТ с нынешним
# belief, то есть ничего не сломано.
cd "$(dirname "$0")/.."
ok=0; fail=0
out=$(sbcl --script test/credal/_check.lisp 2>&1)
while read -r line; do
  case "$line" in
    OK*)   echo "  ✓ ${line#OK }"; ok=$((ok+1));;
    FAIL*) echo "  ✗ ${line#FAIL }"; fail=1;;
  esac
done <<< "$out"
echo "ИТОГ: $ok"
exit $fail
