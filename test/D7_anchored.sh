#!/bin/bash
# D7_anchored — опубликованный якорь сходится с деревом (06.08.2026).
#
# 🔴 ЗАЧЕМ В БАТАРЕЕ, ЕСЛИ ЕСТЬ ОТДЕЛЬНЫЙ `anchor_verify.sh`.
# Отдельный скрипт — для постороннего: одна команда после клона, без веры в нас. Строка в
# батарее — для НАС: чтобы заякоренный субъект не разошёлся с деревом ТИХО. Якорь, о расхождении
# которого узнают через месяц, защищает ровно ничего: к тому времени уже неизвестно, что именно
# менялось и было ли это законно.
#
# ⚠️ Эта проверка обязана иногда падать. Изменили формат субъекта, сцену демонстрации, порядок
# сериализации — она красная, и это ПРАВИЛЬНО: отпечаток обязан двигаться вслед за тем, что он
# отпечатывает. Лечится ДОБАВЛЕНИЕМ якоря в `ANCHORS.md`, не правкой старой строки: правка
# уничтожает единственное, ради чего строка публиковалась.
cd "$(dirname "$0")/.." || exit 1
ok=0; fail=0

if [ ! -x ./anchor_verify.sh ]; then
  echo "  ✗ anchor_verify.sh отсутствует или не исполняем — якорь непроверяем"
  echo "ИТОГ: 0"; exit 1
fi

out=$(./anchor_verify.sh 2>&1); rc=$?
if [ $rc -eq 0 ]; then
  echo "  ✓ опубликованный якорь сходится с деревом (субъект и сцена)"
  ok=2
else
  echo "  ✗ ЯКОРЬ РАЗОШЁЛСЯ С ДЕРЕВОМ:"
  echo "$out" | grep -E "записано|получено|НЕ СОШ" | sed 's/^/    /'
  fail=1
fi

echo "ИТОГ: $ok"
exit $fail
