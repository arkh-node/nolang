#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""classify — разделить подписи уровня модуля на ОПРЕДЕЛЕНИЯ и УТВЕРЖДЕНИЯ.

🔴 ЗАЧЕМ. Счётчик печатал «НЕ РАЗМЕЧЕНО: 221 — это долг». Долг назван честно, но СЛИТЫМ:
в те же 221 попадали определения (`run : List Premise → G`, `_≤ᴳ_ : G → G → Set`), которые
размечать не надо и нельзя — определение не бывает содержательным или определительным, оно
просто определение. Пока они в знаменателе, число говорит «не разобрано 221 теорема», хотя
теорем там вдвое меньше.

🔴 ЭТОТ ФАЙЛ — ЭВРИСТИКА, А НЕ СУДЬЯ. ПРИЧИНА ГЛУБОКАЯ.
Сперва я строил здесь механический критерий, чтобы граница не зависела от вкуса автора:
уменьшая знаменатель, автор поднимает долю доказанного — то есть делает ровно «число,
подросшее от ослабления мерки» (свод контура, 6.9). Опасение верное, а решение оказалось
невозможным, и вот почему.

**В Agda тип И ЕСТЬ утверждение** (соответствие Карри — Ховарда): `run : List Premise → G`
и `ceiling : ∀ c s → …` — объекты одного рода, оба суть типы. Различие «это определение, а
то теорема» **не формальное, а прагматическое**: оно про то, что мы СОБИРАЛИСЬ сказать.
Механический классификатор такого различия не выражает в принципе — он выражает синтаксис.

Отсюда устройство работы:
  · этот файл выдаёт **кандидатов** и грубый счёт — чтобы видеть объём и не потерять строку;
  · **решает автор, читая**, и записывает решение маркером ПРЯМО НАД утверждением;
  · проверяемость даёт не алгоритм, а то, что разметка **лежит рядом с предметом**: любой
    читающий видит и утверждение, и вердикт о нём, и может не согласиться.
Ответственность так не размывается, а называется по имени — это и есть защита от 6.9.

Эвристика (грубая, ошибается в обе стороны):
    похоже на УТВЕРЖДЕНИЕ — в типе есть ≡ ≤ < > ≥ ∈ ⊑ ≢ ≰ либо ¬
    похоже на ОПРЕДЕЛЕНИЕ — результат ведёт в Set/Set₁ или в носитель

⚠️ ДВЕ ЛОВУШКИ, НА ОБЕИХ Я ПОЙМАЛСЯ, ОБЕ ЗАПИСАНЫ ЧТОБЫ НЕ ВЕРНУЛИСЬ:

 1. Смотреть ТИП, а не имя. `_≤ᴳ_ : G → G → Set` — знак в имени, а это определение самого
    отношения. Тип начинается после первого " : ".

 2. 🔴 ПОДПИСЬ В AGDA МНОГОСТРОЧНА. Первая версия жила грепом по одной строке и на
    `Precondition.agda` дала 1 утверждение при 6 уже размеченных руками — противоречие,
    которое и вскрыло дефект. У `blocked-where-needed : ∀ (pre post : Pred)` в первой строке
    пропозиционального знака нет вовсе, он ниже. Мерка по ВИДУ СТРОКИ вместо СТРУКТУРЫ — тот
    же дефект, что дважды ловился в счётчиках этого проекта. Тип собирается целиком, до
    начала уравнения или до следующей подписи.
"""
import re, sys, os, glob

# ¬ добавлено после разбора Precondition: утверждение бывает выражено отрицанием
# предиката, без единого знака сравнения. Результат в Set/Set₁ — признак определения.
PROP = re.compile(r'[≡≤<>≥∈⊑≢≰¬]')
ENDS_SET = re.compile(r'(→|^)\s*Set[₀-₉]*\s*$')
SIG  = re.compile(r'^( {0,2})([^ ()|{}·\-][^ ]*) : (.*)$')

def signatures(path):
    """Выдаёт (имя, полный_тип, номер_строки) для подписей уровня модуля."""
    lines = open(path, encoding='utf-8').read().split('\n')
    out, i = [], 0
    while i < len(lines):
        m = SIG.match(lines[i])
        if not m:
            i += 1
            continue
        indent, name, rest = m.group(1), m.group(2), m.group(3)
        typ, j = [rest], i + 1
        # тип продолжается, пока строки ГЛУБЖЕ подписи и не начинают уравнение/новую подпись
        while j < len(lines):
            nxt = lines[j]
            if not nxt.strip():
                break
            if SIG.match(nxt):
                break
            # уравнение начинается с самого имени на том же отступе
            if re.match(r'^' + re.escape(indent) + re.escape(name) + r'[ ({]', nxt):
                break
            if not nxt.startswith(indent + ' '):
                break
            typ.append(nxt.strip())
            j += 1
        out.append((name, ' '.join(typ), i + 1))
        i = j if j > i else i + 1
    return out

def main():
    d = os.path.dirname(os.path.abspath(__file__))
    dt = ct = 0
    verbose = '-v' in sys.argv
    for f in sorted(glob.glob(os.path.join(d, '*.agda'))):
        defs = claims = 0
        for name, typ, ln in signatures(f):
            is_def = bool(ENDS_SET.search(typ))
            if PROP.search(typ) and not is_def:
                claims += 1
                if verbose:
                    print(f"  УТВ  {os.path.basename(f)}:{ln}  {name}")
            else:
                defs += 1
                if verbose:
                    print(f"  опр  {os.path.basename(f)}:{ln}  {name}")
        print(f"{os.path.basename(f):<26} определений {defs:3} · утверждений {claims:3}")
        dt += defs; ct += claims
    print("─" * 40)
    print(f"ОПРЕДЕЛЕНИЙ (размечать нечего):  {dt}")
    print(f"УТВЕРЖДЕНИЙ (подлежат разметке): {ct}")
    print(f"ВСЕГО подписей:                  {dt+ct}")

if __name__ == '__main__':
    main()
