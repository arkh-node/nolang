#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""mark — проставить маркеры разметки над подписями. Вспомогательный инструмент.

Употребление:  python3 mark.py Файл.agda имя=род имя=род ...
   род ∈ {с, о, д}  →  ⟦содержательное⟧ · ⟦определительное⟧ · ⟦определение⟧

🔴 ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ: он НЕ решает, каков род утверждения. Решение принимает автор,
читая утверждение; инструмент лишь ставит строку туда, где она нужна, и не дублирует уже
стоящую. Родовое решение машинно невыразимо — в Agda тип и есть утверждение (Карри — Ховард),
см. шапку classify.py.

⚠️ Маркер ставится с ТЕМ ЖЕ отступом, что и подпись: счётчик считает отступ 0 или 2, и
несовпадение отступа означало бы, что разметка есть, а в счёт не идёт — то есть долг выглядел
бы вечным при сделанной работе.
"""
import re, sys

ROD = {'с': 'содержательное', 'о': 'определительное', 'д': 'определение'}

def main():
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(2)
    path = sys.argv[1]
    want = {}
    for a in sys.argv[2:]:
        if a == '--reset':
            continue
        name, _, r = a.rpartition('=')
        if r not in ROD:
            print(f"неизвестный род: {r}"); sys.exit(2)
        want[name] = ROD[r]

    lines = open(path, encoding='utf-8').read().split('\n')

    # 🔴 --reset: снять СТОЯЩИЕ маркеры перед расстановкой. Заведён 06.08.2026, когда
    # выяснилось, что часть старых маркеров привязана НЕ К ТОМУ: в ReEntry ⟦содержательное⟧
    # стояло над заголовком раздела, а первой подписью раздела оказалось ОПРЕДЕЛЕНИЕ `_++_` —
    # вердикт достался ему, а настоящая теорема раздела осталась без вердикта. Счётчик при
    # этом показывал бодрое число: он грепает маркеры, а не сверяет их с предметом.
    # Мораль: разметка, не привязанная к утверждению вплотную, считается — но не значит.
    if '--reset' in sys.argv:
        lines = [l for l in lines if not re.match(r'^ {0,2}-- ⟦\w+⟧\s*$', l)]

    out, done = [], set()
    for ln in lines:
        m = re.match(r'^( {0,2})([^ ()|{}·\-][^ ]*) :(?: |$)', ln)
        if m and m.group(2) in want and m.group(2) not in done:
            if not (out and '⟦' in out[-1]):
                out.append(f"{m.group(1)}-- ⟦{want[m.group(2)]}⟧")
            done.add(m.group(2))
        out.append(ln)
    open(path, 'w', encoding='utf-8').write('\n'.join(out))

    missing = set(want) - done
    print(f"{path}: размечено {len(done)} из {len(want)}"
          + (f" · НЕ НАЙДЕНЫ: {sorted(missing)}" if missing else ""))
    if missing:
        sys.exit(1)

if __name__ == '__main__':
    main()
