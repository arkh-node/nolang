#!/usr/bin/env bash
# formal/count.sh — ТРИ ЧИСЛА РАЗДЕЛЬНО (этап 3, пункт 6 критерия). Невис, 31.07.2026.
#
# 🔴 ЗАЧЕМ. Батарея печатала ОДНО число — «законов, проверок и утверждений: 770». Оно
#    складывает вещи разного рода: содержательную теорему, определение, развёрнутое в
#    равенство, и прогон на случайных входах. Сложение разных родов — ровно то отмывание
#    счётом, за которое язык поймал своих авторов в первый же день: 605 зелёных проверок
#    получили вес 605 независимых голосов, хотя это ОДИН факт.
#
# 🔴 КАК РАЗЛИЧАЮТСЯ. Не машиной — автором, маркером в комментарии над утверждением:
#      ⟦содержательное⟧   потребляет гипотезы · не доказуемо как id · ложность что-то ломает
#      ⟦определительное⟧  верно по определениям; ступень, а не доказательство
#    Машинно отличить одно от другого надёжно нельзя, а угадывать — значит врать красиво.
#    Зато НЕРАЗМЕЧЕННОЕ считается и печатается отдельно: «не размечено» — это не ноль и не
#    успех, это признание, что данное утверждение через второй гейт не проходили.
set -u
cd "$(dirname "$0")" || exit 2

meaningful=0; definitional=0; total=0
for f in *.agda; do
  [ -e "$f" ] || continue
  # 🔴 Маркер засчитывается ТОЛЬКО с отступом ровно в два пробела — то есть стоящий над
  #    самим утверждением, а не в шапке файла, где эти же слова объясняются. Первый прогон
  #    насчитал на единицу больше: описание разметки посчиталось как разметка.
  m=$(grep -cE '^  -- ⟦содержательное⟧' "$f")
  d=$(grep -cE '^  -- ⟦определительное⟧' "$f")
  # утверждения уровня модуля: структурно (два пробела, не-пробелы, " : "), ASCII-регулярка —
  # многобайтные символы в скобочном классе однажды дали РАЗНЫЙ счёт в скрипте и в оболочке
  t=$(grep -cE '^  [^ ]+ : ' "$f")
  meaningful=$((meaningful+m)); definitional=$((definitional+d)); total=$((total+t))
  printf '%-28s содержательных %2s · определительных %2s · утверждений уровня модуля %2s\n' \
         "$f" "$m" "$d" "$t"
done

unmarked=$((total - meaningful - definitional))
[ "$unmarked" -lt 0 ] && unmarked=0

printf '\nСОДЕРЖАТЕЛЬНЫХ (прошли второй гейт): %s\n' "$meaningful"
printf 'ОПРЕДЕЛИТЕЛЬНЫХ (ступени, не доказательства): %s\n' "$definitional"
printf 'НЕ РАЗМЕЧЕНО: %s — сюда входят и ОПРЕДЕЛЕНИЯ (Act, Pred, ⊑ и прочее),\n' "$unmarked"
printf '              и теоремы, которые через второй гейт НЕ проводили.\n'
printf '              Пока они не разведены, число «не размечено» — это долг, а не итог.\n'
printf 'MARKUP meaningful=%s definitional=%s unmarked=%s\n' \
       "$meaningful" "$definitional" "$unmarked"
