#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gate2 — ВТОРОЙ ГЕЙТ по ЗАКОНУ XII (Невис). Проверка содержательных утверждений.

🔴 ПОВОД. 07.08.2026 Невис разобрала мой счёт теорем на два слоя:
  · БУХГАЛТЕРИЯ честна и самопроверяема (сумма родов + долг = число подписей, иначе падение);
  · СМЫСЛОВОЕ деление «содержательное/определительное» count.py НЕ гарантирует и по построению
    не может — граница по Карри–Ховарду неразрешима, её ставит рукой автор.
Её вывод: «один модуль ≠ все 65», и настоящий ответ на «не польстил ли себе» даёт только
второй гейт, прогнанный по КАЖДОМУ утверждению.

ТРИ ВОПРОСА ЗАКОНА XII:
  1. потребляет ли доказательство ГИПОТЕЗЫ (а не только ∀-связанные переменные)?
  2. доказуемо ли как `id` — то есть тривиально (refl, сам аргумент, конструктор)?
  3. что сломается В РЕАЛЬНОСТИ, если оно ложно?

🔴 ЧТО ЗДЕСЬ МАШИННОЕ, А ЧТО НЕТ — И ПОЧЕМУ ЭТО РАЗДЕЛЕНО ЯВНО.
Вопросы 1 и 2 — про СИНТАКСИС доказательства, они проверяемы и проверяются здесь.
Вопрос 3 — про МИР, машине недоступен вовсе: «что сломается, если ложно» есть утверждение о
последствиях, а не о тексте. Его отвечает автор, и ответ пишется В ФАЙЛ рядом с теоремой.
Смешивать нельзя: иначе зелёный вывод скрипта прочитается как «гейт пройден», хотя пройдена
только его механическая треть.

Употребление:
    gate2.py            — сводка: кто подозрителен
    gate2.py -v         — построчно, с типом и телом доказательства
"""
import re, os, glob, sys

MARK_C = re.compile(r'^ {0,2}-- ⟦содержательное⟧\s*$')
SIG    = re.compile(r'^( {0,2})([^ ()|{}·\-][^ ]*) :(?: (.*)|$)')

# тривиальные тела: refl, конструктор без разбора, тождество
TRIVIAL = re.compile(r'^\s*(refl|tt|_|\(\)|[a-zA-Z0-9₀-₉\'-]+)\s*$')

def тело(lines, i, name, indent):
    """Собрать правую часть уравнений для имени name, начиная со строки i."""
    out = []
    pat = re.compile(r'^' + re.escape(indent) + re.escape(name) + r'[ ({]')
    for j in range(i, min(i + 40, len(lines))):
        if pat.match(lines[j]):
            # 🔴 `rewrite` — ЧАСТЬ ДОКАЗАТЕЛЬСТВА, а не украшение (поправка 07.08.2026).
            # `f x p rewrite p = refl` выглядит как тривиальное `refl`, но гипотеза `p`
            # потребляется именно переписыванием. Детектор её терял и дважды пометил
            # содержательные теоремы подозрительными — я разобрал их руками и вернул.
            # Мерка, не видящая половины конструкции, мерит не ту величину.
            if ' rewrite ' in lines[j]:
                out.append('rewrite:' + lines[j].split(' rewrite ', 1)[1].strip())
                continue
            eq = lines[j].split('=', 1)
            if len(eq) == 2:
                out.append(eq[1].strip())
            else:                       # тело на следующей строке
                if j + 1 < len(lines):
                    out.append(lines[j + 1].strip())
    return out

def анализ(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    res = []
    for i, ln in enumerate(lines):
        if not MARK_C.match(ln):
            continue
        m = SIG.match(lines[i + 1]) if i + 1 < len(lines) else None
        if not m:
            continue
        indent, name, first = m.group(1), m.group(2), (m.group(3) or '')
        # полный тип: до начала уравнения
        typ = [first]
        j = i + 2
        while j < len(lines):
            nxt = lines[j]
            if not nxt.strip() or SIG.match(nxt): break
            if re.match(r'^' + re.escape(indent) + re.escape(name) + r'[ ({]', nxt): break
            if not nxt.startswith(indent + ' '): break
            typ.append(nxt.strip()); j += 1
        typ = ' '.join(typ)
        bodies = тело(lines, j, name, indent)

        # ── вопрос 1: потребляет ли ГИПОТЕЗЫ ────────────────────────────────
        # ∀-связывание переменных гипотезой не является. Гипотеза — посылка перед →,
        # которая сама есть утверждение (содержит ≡ ≤ ∈ ⊑ ¬ …), либо именованный аргумент
        # доказательного типа.
        без_кванторов = re.sub(r'∀[^→]*?→', '→', typ)
        посылки = [p for p in без_кванторов.split('→')[:-1]]
        гипотезы = [p for p in посылки if re.search(r'[≡≤<>≥∈⊑≢≰¬]', p)]
        q1 = len(гипотезы) > 0

        # ── вопрос 2: доказуемо ли тривиально ───────────────────────────────
        q2_trivial = bool(bodies) and all(TRIVIAL.match(b or '') for b in bodies)

        res.append(dict(файл=os.path.basename(path), имя=name, тип=typ,
                        тела=bodies, потребляет=q1, тривиально=q2_trivial))
    return res

def main():
    d = os.path.dirname(os.path.abspath(__file__))
    все = []
    for f in sorted(glob.glob(os.path.join(d, '*.agda'))):
        все += анализ(f)

    # 🔴 ПОПРАВКА ПОСЛЕ ПЕРВОГО ПРОГОНА (07.08.2026). Первая редакция считала подозрительным
    # всё, что «не потребляет гипотез» — и пометила 38 из 65, включая `preservation`, ГЛАВНУЮ
    # теорему проекта. Критерий был применён механически и неверно: утверждение вида
    # `∀ x → f x ≡ g x`, где f и g определены НЕЗАВИСИМО, гипотез не потребляет, но связывает
    # два разных вычисления — это и есть содержание. «Потребляет гипотезы» работает для
    # импликаций и НЕ работает для свойств функций.
    # Главный механический признак — ТРИВИАЛЬНОСТЬ ТЕЛА: доказано `refl` без лемм и rewrite,
    # то есть верно по определению. Отсутствие гипотез оставлено как ВТОРОЙ, слабый признак:
    # оно подозрительно лишь вместе с тривиальным телом.
    подозр = [r for r in все if r['тривиально']]
    слабые = [r for r in все if not r['потребляет'] and not r['тривиально']]
    verbose = '-v' in sys.argv

    print(f"СОДЕРЖАТЕЛЬНЫХ ВСЕГО: {len(все)}")
    print(f"🔴 ПОДОЗРИТЕЛЬНЫХ (не потребляют гипотез ИЛИ доказаны тривиально): {len(подозр)}")
    print("─" * 78)
    for r in подозр:
        причины = []
        if not r['потребляет']: причины.append("НЕ потребляет гипотез")
        if r['тривиально']:     причины.append(f"тривиальное тело: {r['тела'][:2]}")
        print(f"  {r['файл']:<22} {r['имя']:<28} {' · '.join(причины)}")
        if verbose:
            print(f"      тип: {r['тип'][:110]}")
    print("─" * 78)
    print(f"чистых по вопросам 1–2: {len(все) - len(подозр)} из {len(все)}")
    print()
    print(f"ℹ️  БЕЗ ГИПОТЕЗ, НО С НЕТРИВИАЛЬНЫМ ДОКАЗАТЕЛЬСТВОМ: {len(слабые)}")
    print("   Это НЕ подозрительные: свойство функции (`∀ x → f x ≡ g x` при разных f и g)")
    print("   гипотез не потребляет по форме, а содержание несёт. Перечислены для вопроса 3.")
    if verbose:
        for r in слабые:
            print(f"     {r['файл']:<22} {r['имя']}")
    print()
    print("⚠️ ЭТО ТОЛЬКО ДВЕ ТРЕТИ ГЕЙТА. Вопрос 3 («что сломается в реальности, если ложно»)")
    print("   машине недоступен: это утверждение о последствиях, а не о тексте. Отвечает автор,")
    print("   и ответ пишется в файл рядом с теоремой. Зелёный вывод здесь ≠ гейт пройден.")

if __name__ == '__main__':
    main()
