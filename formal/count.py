#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""count — три числа раздельно, считанные ПО ПРИВЯЗКЕ К УТВЕРЖДЕНИЮ.

Наследует замысел `count.sh` (Невис, 31.07.2026): не складывать в одно число теорему,
определение и прогон на случайных входах — разные рода.

🔴 ПОЧЕМУ ПЕРЕПИСАН НА РАЗБОР (06.08.2026). Прежний счёт был ГРЕПОМ по маркерам, и потому
считал СЛОВА, а не предмет. Два следствия вскрылись подряд:

  1. **Двойной счёт.** В `Precondition.agda` над каждой теоремой стоит пояснительный блок,
     который сам начинается маркером: `-- ⟦содержательное⟧ ТЕОРЕМА 1 (blocked-where-needed).`
     Греп засчитывал и его, и разметку над подписью — пять теорем превращались в десять.
     Значит прежнее «содержательных: 10» по всему проекту было ЗАВЫШЕНО, и неизвестно
     насколько: число собиралось из двух разных вещей.

  2. **Разметка не того.** В `ReEntry.agda` маркер стоял над заголовком раздела, а первой
     подписью раздела оказалось ОПРЕДЕЛЕНИЕ `_++_` — вердикт достался ему, а теорема раздела
     осталась без вердикта. Греп и это считал успехом.

Общее у обоих: **маркер, не привязанный к утверждению, считается, но ничего не значит.**
Здесь вердикт засчитывается, только если непосредственно под ним стоит подпись уровня модуля.
Тогда сумма родов не может разойтись с числом подписей — это проверяется и печатается.

Рода:
  ⟦содержательное⟧   про ПРЕДМЕТ языка; ложность сломала бы гарантию
  ⟦определительное⟧  про ИНСТРУМЕНТ (равенство, решётка, арифметика); ступень
  ⟦определение⟧      не утверждение вовсе: функция, тип, конструктор, носитель
"""
import re, os, glob, sys

SIG  = re.compile(r'^( {0,2})([^ ()|{}·\-][^ ]*) :(?: |$)')
MARK = re.compile(r'^ {0,2}-- ⟦(содержательное|определительное|определение)⟧\s*$')

def scan(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    counts = {'содержательное': 0, 'определительное': 0, 'определение': 0}
    total = unmarked = 0
    naked = []
    for i, ln in enumerate(lines):
        if not SIG.match(ln):
            continue
        total += 1
        m = MARK.match(lines[i-1]) if i else None
        if m:
            counts[m.group(1)] += 1
        else:
            unmarked += 1
            naked.append((i + 1, SIG.match(ln).group(2)))
    return counts, total, unmarked, naked

def main():
    d = os.path.dirname(os.path.abspath(__file__))
    tot = {'содержательное': 0, 'определительное': 0, 'определение': 0}
    T = U = 0
    show = '-v' in sys.argv
    for f in sorted(glob.glob(os.path.join(d, '*.agda'))):
        c, t, u, naked = scan(f)
        print(f"{os.path.basename(f):<26} содержательных {c['содержательное']:3} · "
              f"определительных {c['определительное']:3} · определений {c['определение']:3} · "
              f"без вердикта {u:3} · подписей {t:3}")
        if show and naked:
            for ln, name in naked:
                print(f"      без вердикта: {os.path.basename(f)}:{ln}  {name}")
        for k in tot: tot[k] += c[k]
        T += t; U += u
    print("─" * 46)
    print(f"СОДЕРЖАТЕЛЬНЫХ (про предмет языка):     {tot['содержательное']}")
    print(f"ОПРЕДЕЛИТЕЛЬНЫХ (ступени, не теоремы):  {tot['определительное']}")
    print(f"ОПРЕДЕЛЕНИЙ (размечать нечего):         {tot['определение']}")
    print(f"БЕЗ ВЕРДИКТА: {U} — через второй гейт НЕ проводили. Это долг, а не итог.")
    s = sum(tot.values()) + U
    if s != T:
        print(f"❌ СУММА НЕ СХОДИТСЯ: {s} ≠ {T} подписей — счётчик врёт, чинить его.")
        sys.exit(1)
    print(f"сумма родов + долг = {s} = число подписей ✓")
    print(f"MARKUP meaningful={tot['содержательное']} definitional={tot['определительное']} "
          f"definitions={tot['определение']} unmarked={U}")

if __name__ == '__main__':
    main()
