#!/usr/bin/env bash
# nolang — сборка ОРАКУЛА: доказанная модель (formal/Preservation.agda) штатным
# бэкендом Agda в исполнимое. Дальше test/D1_oracle.lisp гоняет против него Лисп.
#
# 🔴 Почему это не «ещё один тест»: дифференциальный тест сравнивает две НЕПРОВЕРЕННЫЕ
# реализации и не ловит их общую ошибку. Оракул берёт одну сторону из Agda, где степень
# доказана, — и общая ошибка становится невозможной с той стороны, где доказано.
#
# 🔴 Чего он НЕ делает: не доказывает эквивалентность. Ограничивает расхождение ЧИСЛОМ
# ИСПЫТАНИЙ. Так и печатается в батарее.
set -eu
cd "$(dirname "$0")"

command -v agda >/dev/null || { echo "agda не найдена — оракул собрать нечем"; exit 1; }
command -v ghc  >/dev/null || { echo "ghc не найден — у Agda нет бэкенда"; exit 1; }

mkdir -p build
# -i../formal: модель лежит там и остаётся --safe; этот драйвер — НЕ safe (в нём есть
# постулаты ввода-вывода) и НЕ в formal/, чтобы батарея не считала его теоремами.
agda -i. -i../formal --compile --compile-dir=build Oracle.agda

test -x build/Oracle || { echo "бинарь не появился — сборка солгала"; exit 1; }

# смоук на трёх ручных примерах: собралось ≠ считает верно
got=$(printf '1 2 0 1 2 0 2 1 0\n1 2 0 1 3 1 2 0\n2 2 0 1 2 0 0 2 1 3 0\n' | ./build/Oracle | tr -d ' ')
want=$(printf '11|11\n0|0\n210|210')
[ "$got" = "$want" ] || { echo "СМОУК ПРОВАЛЕН:"; echo "получено: $got"; echo "ждали:    $want"; exit 1; }

echo "оракул собран и считает верно на смоуке: oracle/build/Oracle"
